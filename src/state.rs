use std::path::PathBuf;
use std::sync::atomic::AtomicU64;
use std::sync::Arc;

use actix::prelude::*;
use serde_json::Value;
use sqlx::SqlitePool;

use crate::config::Config;
use crate::realtime::{Hub, Push, ToUser, ToUsers};

pub struct AppState {
    pub pool: SqlitePool,
    pub hub: Addr<Hub>,
    pub cfg: Config,
    pub start_ms: i64,
    pub version: &'static str,
    pub hostname: String,
    pub build: String,
    pub max_upload: AtomicU64,
}

impl AppState {
    pub fn new(pool: SqlitePool, hub: Addr<Hub>, cfg: Config) -> Self {
        let hostname = hostname();
        AppState {
            pool,
            hub,
            cfg,
            start_ms: crate::util::now_ms(),
            version: env!("CARGO_PKG_VERSION"),
            hostname,
            build: "release".into(),
            max_upload: AtomicU64::new(cfg.max_upload),
        }
    }

    pub fn uptime_ms(&self) -> i64 {
        (crate::util::now_ms() - self.start_ms).max(0)
    }

    pub fn broadcast(&self, v: Value) {
        self.hub.do_send(Push(v));
    }

    pub fn to_user(&self, uid: i64, v: Value) {
        self.hub.do_send(ToUser {
            user_id: uid,
            value: v,
        });
    }

    pub fn to_users(&self, users: Vec<i64>, v: Value) {
        self.hub.do_send(ToUsers {
            users,
            value: v,
        });
    }

    /// Absolute path of a stored blob. Keys are always generated by the server,
    /// so they can never escape the files directory.
    pub fn blob_path(&self, key: &str) -> PathBuf {
        self.cfg.files_dir.join(key)
    }

    pub async fn audit(
        &self,
        actor_id: i64,
        actor_name: &str,
        action: &str,
        entity: &str,
        entity_id: i64,
        detail: &str,
        ip: &str,
    ) {
        crate::store::audit(
            &self.pool,
            actor_id,
            actor_name,
            action,
            entity,
            entity_id,
            detail,
            ip,
        )
        .await;
    }
}

pub fn hostname() -> String {
    std::env::var("HOSTNAME")
        .ok()
        .filter(|s| !s.is_empty())
        .or_else(|| {
            std::fs::read_to_string("/etc/hostname")
                .ok()
                .map(|s| s.trim().to_string())
                .filter(|s| !s.is_empty())
        })
        .unwrap_or_else(|| "local".into())
}

pub type Shared = Arc<AppState>;
